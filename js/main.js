// arithmetics

// addition
const x = 50 + 40;
console.log(x);

const y = x + 50;
console.log(y);

const z = x + y;
console.log(z);

// subtraction
console.log(y - z);

// multiplication
console.log(x * y);

// division
console.log(x / y);

// modulus
console.log(x % y);

// exponent
console.log(x ** y);

// increment
let a = 1;
console.log(a++);
console.log(++a);

// decrement
console.log(a--);
console.log(--a);

// assignment
a += 5;
console.log(a);

a -= 3;
console.log(a);

a *= 3;
console.log(a);

a /= 2;
console.log(a);

a %= 2;
console.log(a);

a **= 2;
console.log(a);
